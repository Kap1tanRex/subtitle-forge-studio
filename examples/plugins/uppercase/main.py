"""Пример плагина: показывает всё, что нужно знать, чтобы написать свой.

Положите папку с этим файлом и plugin.json в каталог плагинов (он указан в
«Настройки → Плагины»), включите загрузку плагинов и перезапустите
программу. Пункт появится в меню «Плагины».

Плагин обязан определить одну функцию — setup(context). Всё остальное он
делает через context: программа не требует ни наследования, ни импортов
своих внутренних модулей. Так плагин переживает обновления: меняется
внутреннее устройство программы, а контекст остаётся.
"""


def setup(context):
    """Вызывается один раз при загрузке."""

    def shout():
        # Счётчик в собственном разделе настроек: чужие разделы плагину
        # недоступны, и испортить настройки программы он не может.
        used = int(context.store("used", 0)) + 1
        context.set_store("used", used)
        context.log(f"пункт вызван {used}-й раз")

    context.register_action(
        "shout",
        "Пример: сказать в журнал",
        shout,
        tooltip="Показывает, что плагин работает",
    )
