import sys
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "build" / "onefile.spec"
DIST = ROOT / "dist"
EXE_NAME = "SubtitleForgeStudio.exe"

