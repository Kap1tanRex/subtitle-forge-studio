"""Сборка и раскладка готового к проверке комплекта.

Собирает бинарник и кладёт его в отдельную папку **вне** дерева проекта,
вместе с короткой запиской о том, что проверять. Причина простая: ``dist``
перезаписывается при каждой сборке и лежит среди исходников, а человеку,
который просто хочет запустить программу, ходить туда незачем.

Запуск::

    python build/release.py                # собрать и разложить
    python build/release.py --no-build     # только разложить готовый exe
    python build/release.py --output ПУТЬ  # другая папка назначения
    python build/release.py --no-cuda      # без библиотек для видеокарты
"""

