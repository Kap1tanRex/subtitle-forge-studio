"""Показ чужого текста в подсказках без разметки.

Qt решает сам, разметка перед ним или обычный текст: строку, похожую на
HTML, подсказка и ``QLabel`` покажут **как HTML**. Текст реплики приходит из
файла, который пользователь скачал со стороны, и содержит что угодно, — а
значит, реплика вида ``<img src="\\\\чужой-сервер\\share\\p.png">`` заставит
Windows пойти на этот сервер и представиться. Проверено: ``QLabel`` с
локальной картинкой в ``<img>`` принимает её размер, то есть ресурс
действительно загружается.

Поэтому чужой текст перед показом экранируется и оборачивается в разметку
явно: так он остаётся ровно тем, что написано в файле, включая переносы
строк и угловые скобки.
"""

from __future__ import annotations

import html

from PySide6.QtGui import Qt

__all__ = ["menu_label", "plain_tooltip"]


def plain_tooltip(text: str) -> str:
    """Готовит текст к показу в подсказке, ничего не выполняя.

    Строка, которую Qt заведомо не примет за разметку, отдаётся как есть:
    оборачивать каждую подсказку — лишняя работа на каждом движении мыши.
    """
    if not text or not Qt.mightBeRichText(text):
        return text
    # ``white-space: pre-wrap`` сохраняет переносы строк, которые в HTML
    # иначе схлопнулись бы в пробелы, — подсказка на несколько строк должна
    # остаться такой же, как её собрали.
    return f"<div style='white-space: pre-wrap'>{html.escape(text)}</div>"


def menu_label(text: str) -> str:
    """Имя для пункта меню.

    Амперсанд в тексте пункта Qt считает признаком горячей буквы: актор
    «Иван & Марья» показался бы как «Иван  Марья» с подчёркнутым пробелом.
    Удвоение возвращает символ на место.
    """
    return text.replace("&", "&&")
