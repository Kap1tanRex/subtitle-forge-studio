"""Общая настройка тестов.

Qt переводится в offscreen-режим до любого импорта PySide6, чтобы GUI-тесты
шли без дисплея — это нужно и для CI, и чтобы прогон не открывал окна.

Внимание: в offscreen-режиме база шрифтов пуста (``QFontDatabase.families()``
возвращает 0). Метрики текста при этом остаются рабочими, но отрисованные
глифы — пустые прямоугольники. Поэтому тесты проверяют геометрию и наличие
непрозрачных пикселей, а не совпадение картинки с эталоном; визуальные
регрессии (§25.2 спецификации) требуют платформы с реальными шрифтами.
"""

from __future__ import annotations

import os

os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")
